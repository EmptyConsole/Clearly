// Formats simulation summaries for docs/sim-results.txt and src/generated/simStats.ts.

import { EXPRESS_PARAMS, REFINE_PARAMS } from '../estimator/params.ts';
import { durationFromStatsSeconds } from '../timing.ts';
import { SIM_RUNS, SIM_SEED_EXPRESS, SIM_SEED_REFINE, type SimSummary } from './run.ts';

const r4 = (x: number): number => Math.round(x * 10000) / 10000;
const pct = (x: number): string => `${(x * 100).toFixed(2)}%`;

export interface GeneratedTrialStats {
  readonly trialsMean: number;
  readonly trialsP95: number;
  readonly toneTrialsMean: number;
  readonly catchTrialsMean: number;
  readonly heardShare: number;
}

export function trialStats(s: SimSummary): GeneratedTrialStats {
  return {
    trialsMean: r4(s.trialsMean),
    trialsP95: r4(s.trialsP95),
    toneTrialsMean: r4(s.toneTrialsMean),
    catchTrialsMean: r4(s.catchTrialsMean),
    heardShare: r4(s.heardShare),
  };
}

export function generatedStatsSource(express: SimSummary, refine: SimSummary): string {
  const obj = (t: GeneratedTrialStats): string =>
    Object.entries(t)
      .map(([k, v]) => `    ${k}: ${String(v)},`)
      .join('\n');
  const body = `{\n  express: {\n${obj(trialStats(express))}\n  },\n  refine: {\n${obj(trialStats(refine))}\n  },\n}`;
  return `// GENERATED by packages/core/scripts/simulate.ts from the fixed-seed simulation. Do not edit.
// Regenerate with: pnpm --filter @clearly/core sim
// The accuracy suite fails if these numbers no longer match a fresh run.

export const SIM_TRIAL_STATS = ${body} as const;
`;
}

function histogram(h: Readonly<Record<number, number>>, runs: number): string {
  const keys = Object.keys(h)
    .map(Number)
    .sort((a, b) => a - b);
  return keys
    .map((k) => {
      const n = h[k] ?? 0;
      const bar = '#'.repeat(Math.max(n > 0 ? 1 : 0, Math.round((n / runs) * 200)));
      return `    ${String(k).padStart(3)} trials  ${String(n).padStart(4)}  ${bar}`;
    })
    .join('\n');
}

function section(s: SimSummary, target: string): string {
  return `${s.method.toUpperCase()} (${s.runs} simulated runs)
  Accuracy (tracks whose true threshold is inside the presentable range)
    measurable tracks             ${s.measurableTracks}
    within ${s.toleranceDb} dB of truth          ${pct(s.withinTolerance)}   target: ${target}
    absolute error P50/P90/P95/P99  ${s.absErrorP50.toFixed(2)} / ${s.absErrorP90.toFixed(2)} / ${s.absErrorP95.toFixed(2)} / ${s.absErrorP99.toFixed(2)} dB
    mean signed error (bias)      ${s.meanSignedErrorDb.toFixed(2)} dB
  Tracks whose truth is beyond the floor or ceiling (not scored for accuracy)
    censored tracks               ${s.censoredTracks}
    of which correctly flagged    ${s.censoredFlagged} (${pct(s.censoredFlagged / Math.max(1, s.censoredTracks))})
  Trials per run (tone plus catch)
    mean ${s.trialsMean.toFixed(2)}, median ${s.trialsP50}, P95 ${s.trialsP95.toFixed(1)}, max ${s.trialsMax}
    tone trials mean ${s.toneTrialsMean.toFixed(2)}, catch trials mean ${s.catchTrialsMean.toFixed(2)} (min ${s.catchTrialsMin})
    share of tone trials answered "heard" ${pct(s.heardShare)}
  Expected duration (timing model, before rounding)
    normal pace ${durationFromStatsSeconds(s, 'normal').toFixed(1)} s, slower pace ${durationFromStatsSeconds(s, 'slower').toFixed(1)} s
  Reliability
    High ${s.reliabilityCounts.High}, Medium ${s.reliabilityCounts.Medium}, Low ${s.reliabilityCounts.Low}
    high-guess listeners rated Low  ${s.highGuessLow} of ${s.highGuessListeners} (${pct(s.highGuessLow / Math.max(1, s.highGuessListeners))})   target: at least 80%
    normal listeners rated Low      ${s.normalLow} of ${s.normalListeners} (${pct(s.normalLow / Math.max(1, s.normalListeners))})   target: at most 5%
  Distribution of trials per run
${histogram(s.trialHistogram, s.runs)}
`;
}

export function formatReport(express: SimSummary, refine: SimSummary): string {
  return `CLEARLY: HEARING CHECK SIMULATION RESULTS
GENERATED by packages/core/scripts/simulate.ts. Do not edit; regenerate with
pnpm --filter @clearly/core sim. Seeds: Express ${SIM_SEED_EXPRESS}, Refine ${SIM_SEED_REFINE}
(each Refine run follows its own Express run on the same simulated listener). ${SIM_RUNS} runs each.
The simulated listener is described in docs/HEARING_MATH.txt, section 6.

Estimator settings
  Express: prior SD ${EXPRESS_PARAMS.priorSdDb} dB, stop SD ${EXPRESS_PARAMS.stopSdDb} dB, trials ${EXPRESS_PARAMS.minTrials} to ${EXPRESS_PARAMS.maxTrials}, jitter +/-${EXPRESS_PARAMS.jitterDb} dB,
           sharing ${EXPRESS_PARAMS.shareSameEar} same ear, ${EXPRESS_PARAMS.shareOtherEar} other ear
  Refine:  stop SD ${REFINE_PARAMS.stopSdDb} dB, trials ${REFINE_PARAMS.minTrials} to ${REFINE_PARAMS.maxTrials}, seeded from the Express posterior

${section(express, 'at least 95%; mean trials at most 36; P95 at most 44')}
${section(refine, 'at least 95%')}`;
}
