// Performance probe (M02 section 7): reports worklet process() times and graph throughput to
// docs/perf.txt. Development only; the numbers depend on the machine.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { cpus } from 'node:os';
import { call, expect, test } from './harness.ts';

interface Perf {
  node: string;
  report: { method: string; calls: number; meanMs: number; maxMs: number; quantumMs: number };
}

test('worklet process() times and graph throughput are reported to docs/perf.txt', async ({
  harness,
  browser,
}) => {
  test.setTimeout(120_000);
  const scope = await call<{ method: string; renderCapacity: boolean }>(
    harness,
    'workletScopeHasPerformance',
  );
  const live = await call<{ overloads: number; perf: Perf[] }>(harness, 'normalRealtime', 4);
  const offline = await call<{
    seconds: number;
    passthroughMs: number;
    graphMs: number;
    graphMsPerQuantum: number;
    realtimeFactor: number;
    perf: Perf[];
  }>(harness, 'offlineThroughput', 60);

  const wasm = new URL('../../apps/web/public/heavy/rnnoise/rnnoise.wasm', import.meta.url);
  const allOn = existsSync(wasm)
    ? await call<{ overloads: number; perf: Perf[] }>(
        harness,
        'perfAllOn',
        readFileSync(wasm).toString('base64'),
      )
    : null;
  const quantumMs = live.perf[0]?.report.quantumMs ?? 128 / 48;
  const liveSum = live.perf.reduce((a, p) => a + p.report.meanMs, 0);
  const lines = [
    'CLEARLY: AUDIO PERFORMANCE (generated by e2e/audio/perf.spec.ts; machine-dependent)',
    `Date: ${new Date().toISOString()}`,
    `Machine: ${cpus()[0]?.model ?? 'unknown'} x${cpus().length}; Chromium ${browser.version()}`,
    `Clock inside AudioWorkletGlobalScope: ${scope.method}` +
      (scope.method === 'date-now-mean'
        ? ' (no performance.now; mean of 1 ms Date.now differences, unbiased over many calls; max is not meaningful)'
        : ''),
    `AudioContext.renderCapacity available: ${scope.renderCapacity}`,
    '',
    'LIVE (AudioContext, 4 s of programme, default settings: cleanup and Night mode off)',
    ...live.perf.map(
      (p) =>
        `  ${p.node.padEnd(16)} mean ${(p.report.meanMs * 1000).toFixed(1).padStart(6)} us per quantum over ${p.report.calls} calls`,
    ),
    `  sum of worklet means: ${(liveSum * 1000).toFixed(1)} us = ${((liveSum / quantumMs) * 100).toFixed(2)}% of one ${quantumMs.toFixed(3)} ms quantum (budget 15% with cleanup on)`,
    '',
    ...(allOn
      ? [
          'LIVE, M06 (Background cleanup 100%, Night mode Strong, Voice focus 100%, 4 s)',
          ...allOn.perf.map(
            (p) =>
              `  ${p.node.padEnd(16)} mean ${(p.report.meanMs * 1000).toFixed(1).padStart(6)} us per quantum over ${p.report.calls} calls`,
          ),
          `  sum of worklet means: ${(allOn.perf.reduce((a, p) => a + p.report.meanMs, 0) * 1000).toFixed(1)} us = ${((allOn.perf.reduce((a, p) => a + p.report.meanMs, 0) / quantumMs) * 100).toFixed(2)}% of one quantum (budget 15%)`,
          '',
        ]
      : ['LIVE, M06: skipped (run pnpm fetch:heavy for the RNNoise module)', '']),
    `OFFLINE (OfflineAudioContext, ${offline.seconds} s of programme, whole graph incl. native nodes)`,
    `  passthrough render ${offline.passthroughMs.toFixed(0)} ms; graph render ${offline.graphMs.toFixed(0)} ms`,
    `  graph cost ${(offline.graphMsPerQuantum * 1000).toFixed(1)} us per quantum; ${offline.realtimeFactor.toFixed(1)}x real time`,
    ...offline.perf.map(
      (p) =>
        `  ${p.node.padEnd(16)} mean ${(p.report.meanMs * 1000).toFixed(1).padStart(6)} us per quantum`,
    ),
    '',
  ];
  // Keep the M11 video export memory section (written by e2e/app/video-memory.spec.ts).
  const perfUrl = new URL('../../docs/perf.txt', import.meta.url);
  const previous = existsSync(perfUrl) ? readFileSync(perfUrl, 'utf8') : '';
  const video = previous.indexOf('VIDEO EXPORT MEMORY');
  writeFileSync(perfUrl, lines.join('\n') + (video >= 0 ? previous.slice(video) : ''));
  expect(live.overloads).toBe(0);
  expect(liveSum / quantumMs).toBeLessThan(0.15);
  if (allOn) {
    expect(allOn.overloads).toBe(0);
    expect(allOn.perf.reduce((a, p) => a + p.report.meanMs, 0) / quantumMs).toBeLessThan(0.15);
  }
});
